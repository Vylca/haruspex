#!/usr/bin/env python3
"""Builds the Haruspex pixel font, PC DOS, from the IBM PC DOS 2000 ISO 9241-3
text mode fonts (8x16). The bitmaps come from VileR's collection,
https://github.com/viler-int10h/vga-text-mode-fonts (FONTS/SYSTEM/PCDOS2K).

Code page 437 is the base. The other ISO code pages (850, 852, 857, 860, 861,
863, 866, 855, 869) add Western and Central European letters, Turkish, Greek
and Cyrillic. A few glyphs no code page has (typographic quotes and dashes,
the euro sign, OE ligatures and the bullets Haruspex uses) are drawn here in
the same style.

Every pixel of the bitmap becomes a square in the outline, so at 16 px (and
32 px, 48 px...) the text renders as crisp pixels.

    python3 tool/build_font.py path/to/FONTS/SYSTEM/PCDOS2K assets/fonts

Needs fontTools (pip install fonttools).
"""

import sys
from pathlib import Path

from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen

FAMILY = "PC DOS"
FILE = "PCDOS"
PX = 64  # font units per pixel: 16 px = 1024 units = 1 em
CELL_W, ASCENT, DESCENT = 8, 12, 4
CELL_H = ASCENT + DESCENT

# Code pages in order of preference: the first one that has a character wins.
