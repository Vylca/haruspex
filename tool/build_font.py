# Same shape as another character.
ALIASES = {0x2010: "-", 0x2011: "-", 0x2212: "-", 0x2219: "·"}


def load_code_page(path, cp):
    """Returns {codepoint: set of (x, y) pixels}, y up from the baseline, for a
    raw VGA font: 256 characters of CELL_H bytes, one bit per pixel."""
    data = Path(path).read_bytes()
    h = len(data) // 256
    assert h == CELL_H, (path, h)
    glyphs = {}
    for code in range(1, 256):
        if cp == "437" and code < 32:
            ch = CP437_LOW[code]
        elif cp == "437" and code == 127:
            ch = CP437_DEL
        elif code < 128:
            if cp != "437":
                continue
            ch = chr(code)
        else:
            try:
                ch = bytes([code]).decode("cp" + cp)
            except UnicodeDecodeError:
                continue
        if ord(ch) < 32 or ord(ch) == 127:
            continue
        pixels = set()
        for r in range(h):
            b = data[code * h + r]
            for c in range(8):
                if b >> (7 - c) & 1:
                    pixels.add((c, ASCENT - 1 - r))
        glyphs[ord(ch)] = pixels
    return glyphs


def parse_art(art):
    rows = art.strip("\n").split("\n")
    assert len(rows) == CELL_H, len(rows)
    pixels = set()
    for r, row in enumerate(rows):
        assert len(row) == CELL_W, row
        for c, ch in enumerate(row):
            if ch == "#":
                pixels.add((c, ASCENT - 1 - r))
    return pixels


def outlines(pixels):
    """Traces the union of the pixel squares into closed contours: clockwise
    outer contours and counter-clockwise holes, as TrueType expects."""
    edges = set()
    for x, y in pixels:
        for e in (((x, y + 1), (x + 1, y + 1)), ((x + 1, y + 1), (x + 1, y)),
                  ((x + 1, y), (x, y)), ((x, y), (x, y + 1))):
            rev = (e[1], e[0])
            if rev in edges:
                edges.remove(rev)
            else:
                edges.add(e)
    out = {}
    for a, b in edges:
        out.setdefault(a, []).append(b)
    loops = []
    while out:
        start = next(iter(out))
        loop = [start]
        prev, cur = None, start
        while True:
            nexts = out[cur]
            if len(nexts) == 1 or prev is None:
                nxt = nexts[0]
            else:
                # Where two pixel corners touch, turn right so the shapes stay apart.
                dx, dy = cur[0] - prev[0], cur[1] - prev[1]
                right = (dy, -dx)
                nxt = next((n for n in nexts if (n[0] - cur[0], n[1] - cur[1]) == right), nexts[0])
            nexts.remove(nxt)
            if not nexts:
                del out[cur]
            prev, cur = cur, nxt
            if cur == start:
                break
            loop.append(cur)
        # Drop points in the middle of straight runs.
        simple = []
        n = len(loop)
        for i in range(n):
            p0, p1, p2 = loop[i - 1], loop[i], loop[(i + 1) % n]
            if (p1[0] - p0[0]) * (p2[1] - p1[1]) != (p1[1] - p0[1]) * (p2[0] - p1[0]):
                simple.append(p1)
        loops.append(simple)
    return loops


def embolden(px):
    """Bitmap bold: every pixel smeared one column sideways, except where that
    would close a one pixel gap (keeps m, w and e readable). Letters leave
    column 0 empty, so they grow to the left and stay inside the cell."""
    if not px:
        return px
    if min(x for x, _ in px) > 0:
        return px | {(x - 1, y) for x, y in px if (x - 2, y) not in px}
    return px | {(x + 1, y) for x, y in px if (x + 2, y) not in px and x + 1 < CELL_W}


def build(glyphs, out_path, bold):
    order = [".notdef"]
    cmap = {}
    shapes = {".notdef": set()}
    for cp in sorted(glyphs):
        name = "space" if cp == 0x20 else f"uni{cp:04X}" if cp <= 0xFFFF else f"u{cp:05X}"
        order.append(name)
        cmap[cp] = name
        shapes[name] = embolden(glyphs[cp]) if bold else glyphs[cp]

    fb = FontBuilder(PX * CELL_H, isTTF=True)
    fb.setupGlyphOrder(order)
    fb.setupCharacterMap(cmap)
    glyf = {}
    for name in order:
        pen = TTGlyphPen(None)
        for loop in outlines(shapes[name]):
            pen.moveTo((loop[0][0] * PX, loop[0][1] * PX))
            for x, y in loop[1:]:
                pen.lineTo((x * PX, y * PX))
            pen.closePath()
        glyf[name] = pen.glyph()
    fb.setupGlyf(glyf)
    metrics = {}
    table = fb.font["glyf"]
    for name in order:
        g = table[name]
        g.recalcBounds(table)
        metrics[name] = (CELL_W * PX, getattr(g, "xMin", 0) if g.numberOfContours else 0)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=ASCENT * PX, descent=-DESCENT * PX, lineGap=0)
    style = "Bold" if bold else "Regular"
    fb.setupNameTable({
        "familyName": FAMILY,
        "styleName": style,
        "uniqueFontIdentifier": f"{FILE}-{style}-Haruspex",
        "fullName": f"{FAMILY} {style}",
        "psName": f"{FILE}-{style}",
        "version": "Version 1.0",
        "copyright": "Bitmaps from the IBM PC DOS 2000 ISO 9241-3 text mode fonts. "
                     "Outline conversion and extra glyphs for Haruspex.",
    })
    fb.setupOS2(
        sTypoAscender=ASCENT * PX, sTypoDescender=-DESCENT * PX, sTypoLineGap=0,
        usWinAscent=ASCENT * PX, usWinDescent=DESCENT * PX,
        sxHeight=7 * PX, sCapHeight=10 * PX,
        usWeightClass=700 if bold else 400,
        fsSelection=0x20 if bold else 0x40,
        achVendID="HRSP",
    )
    fb.font["OS/2"].panose.bProportion = 9  # monospaced
    fb.font["head"].macStyle = 1 if bold else 0
    fb.setupPost(isFixedPitch=1, underlinePosition=-2 * PX, underlineThickness=PX)
    fb.save(out_path)


def main():
    src, out_dir = Path(sys.argv[1]), Path(sys.argv[2])
    out_dir.mkdir(parents=True, exist_ok=True)
    glyphs = {}
    for cp in CODE_PAGES:
        for code, px in load_code_page(src / f"ISOCP{cp}.F16", cp).items():
            glyphs.setdefault(code, px)
    for code, art in EXTRA.items():
        glyphs.setdefault(code, parse_art(art))
    for code, same in ALIASES.items():
        glyphs.setdefault(code, glyphs[ord(same)])
    build(glyphs, out_dir / f"{FILE}-Regular.ttf", bold=False)
    build(glyphs, out_dir / f"{FILE}-Bold.ttf", bold=True)
    print(f"{len(glyphs)} glyphs written to {out_dir}")


if __name__ == "__main__":
    main()
